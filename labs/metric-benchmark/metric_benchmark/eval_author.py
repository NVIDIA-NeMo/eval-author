"""Translate a coverage request into Eval Author audit measurement and reporting."""

import argparse
import subprocess
import sys
from pathlib import Path
from typing import Literal

from pydantic import Field

from metric_benchmark.config import file_manifest
from metric_benchmark.io import cli, digest_bytes, json_bytes, read_json, write_json
from metric_benchmark.models import Digest, Model, Score, Text, resolve_evidence


class EvalAuthorSettings(Model):
    eval_author_root: Text
    source_sha256: Digest
    author_command: list[Text] = Field(min_length=1)
    methods: list[Literal["tool_calls", "capabilities", "failure_cases"]] = Field(
        default=["tool_calls", "capabilities", "failure_cases"],
        min_length=1,
    )
    score_scope: Literal["overall", "tool", "capability", "failure_case"] = "overall"


def source_digest(root: Path) -> str:
    """Pin the audit implementation and schemas, excluding generated bytecode."""
    files = file_manifest(root / "skills/eval-author-audit")
    return digest_bytes(json_bytes({k: v for k, v in files.items() if k.endswith((".py", ".json"))}))


def _run(command: list[str], log_name: str) -> None:
    with Path(log_name).open("wb") as log:
        result = subprocess.run(command, stdout=log, stderr=subprocess.STDOUT, check=False)
    if result.returncode:
        raise ValueError(f"Eval Author command failed ({result.returncode}); see {log_name}")


def _unjudged(value: object) -> bool:
    if isinstance(value, dict):
        return value.get("status") in ("unjudged", "unsupported") or any(_unjudged(v) for v in value.values())
    if isinstance(value, list):
        return any(_unjudged(v) for v in value)
    return False


def compute_eval_author(request_path: Path) -> Score:
    """Author an audit for this subset, measure its traces, and aggregate coverage.

    The supplied author command is the system under evaluation's invocation. It
    creates authored/audit.md and authored/judgments.json (task ID -> optional
    capability_judgments/failure_case_judgments paths relative to authored/).
    Authoring may involve a model; measurement and orchestration do not decide
    what the model should say. Existing coverage receipts replay its observations.
    """
    request = read_json(request_path)
    if not isinstance(request, dict):
        raise ValueError("coverage request must be an object")
    settings = EvalAuthorSettings.model_validate(request["settings"])
    root = Path(settings.eval_author_root)
    if not root.is_absolute() or source_digest(root) != settings.source_sha256:
        raise ValueError("Eval Author source identity differs")
    if not Path(settings.author_command[0]).is_absolute():
        raise ValueError("author command executable must be absolute")
    if len(set(settings.methods)) != len(settings.methods):
        raise ValueError("duplicate measurement methods")
    script_root = root / "skills/eval-author-audit/scripts/audit_spec"
    _run([*settings.author_command, "--request", str(request_path), "--output-dir", "authored"], "author.log")
    audit = resolve_evidence(Path("authored"), "audit.md").relative_to(Path.cwd())
    judgments = read_json(resolve_evidence(Path("authored"), "judgments.json"))
    task_ids = {item["task"]["task_id"] for item in request["baseline_evidence"]}
    if not isinstance(judgments, dict) or set(judgments) - task_ids:
        raise ValueError("judgments must be keyed by this subset's task IDs")
    for index, item in enumerate(request["baseline_evidence"]):
        if item["format"] != "directory":
            raise ValueError("Eval Author adapter requires unpacked Harbor trial directories")
        native = resolve_evidence(Path("."), item["path"])
        trace = resolve_evidence(native, "agent/trajectory.json").relative_to(Path.cwd())
        # Eval Author rejects repeated run IDs across a subset. Derive each
        # measurement identity from its task rather than a fresh Harbor UUID.
        command = [
            sys.executable,
            "-B",
            str(script_root / "measure.py"),
            "--audit",
            str(audit),
            "--trace",
            str(trace),
            "--task-id",
            item["task"]["task_id"],
            "--run-id",
            "baseline:" + item["task"]["task_id"],
            "--evidence-class",
            "agent_under_test",
            "--out-dir",
            "measurements",
            "--measure",
            ",".join(settings.methods),
        ]
        sidecars = judgments.get(item["task"]["task_id"], {})
        if not isinstance(sidecars, dict) or set(sidecars) - {"capability_judgments", "failure_case_judgments"}:
            raise ValueError("unknown judgment sidecar field")
        for kind, path in sorted(sidecars.items()):
            command += [
                "--" + kind.replace("_", "-"),
                str(resolve_evidence(Path("authored"), path).relative_to(Path.cwd())),
            ]
        _run(command, f"measure-{index:06d}.log")
    reports = sorted(Path("measurements").glob("task=*/run=*/*/coverage.json"))
    if len(reports) != len(task_ids) * len(settings.methods):
        raise ValueError("measurement output count differs from requested tasks and methods")
    command = [sys.executable, "-B", str(script_root / "report.py"), "--audit", str(audit), "--out", "report.json"]
    for report in reports:
        command += ["--coverage", str(report)]
    _run(command, "report.log")
    report = read_json(Path("report.json"))
    if not isinstance(report, dict):
        raise ValueError("invalid Eval Author report")
    for details in sorted(Path("measurements").glob("task=*/run=*/*/details.json")):
        if _unjudged(read_json(details)):
            return Score(
                value=None,
                missing_score_reason=f"Eval Author evidence requires missing or unsupported judgments: {details}",
            )
    coverage = report["coverage"]
    scope = settings.score_scope
    counts = coverage["overall"] if scope == "overall" else coverage["by_kind"][scope]
    required_kinds = [
        kind for kind, v in coverage["by_kind"].items() if v["item_count"] and (scope == "overall" or scope == kind)
    ]
    if set(required_kinds) - set(report["measured_kinds"]):
        return Score(
            value=None,
            missing_score_reason="coverage denominator includes unmeasured item kinds: "
            + ", ".join(sorted(set(required_kinds) - set(report["measured_kinds"]))),
        )
    total = counts["item_count"]
    if not total:
        return Score(value=None, missing_score_reason="empty coverage denominator")
    return Score(value=counts["covered_count"] / total)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    mode = parser.add_mutually_exclusive_group(required=True)
    mode.add_argument("--request", type=Path)
    mode.add_argument("--print-source-digest", type=Path, metavar="EVAL_AUTHOR_ROOT")
    parser.add_argument("--output", type=Path)

    def run(args):
        if args.print_source_digest:
            if args.output:
                parser.error("--output is only valid with --request")
            print(source_digest(args.print_source_digest.resolve()))
        else:
            if not args.output:
                parser.error("--request requires --output")
            write_json(args.output, compute_eval_author(args.request))

    cli(parser, run)
